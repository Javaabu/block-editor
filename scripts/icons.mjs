// Writes resources/js/editor/ui/icons.ts from lucide-static: the inner SVG of each
// icon the editor uses. Run `node scripts/icons.mjs` after changing the list.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"

const require = createRequire(import.meta.url)
const root = join(dirname(require.resolve("lucide-static/package.json")), "icons")

const icons = [
  "arrow-down",
  "arrow-up",
  "between-horizontal-end",
  "between-horizontal-start",
  "between-vertical-end",
  "between-vertical-start",
  "blocks",
  "bold",
  "circle-alert",
  "code",
  "code-xml",
  "columns-2",
  "copy",
  "grip-vertical",
  "heading",
  "image",
  "info",
  "italic",
  "languages",
  "link",
  "list",
  "list-ordered",
  "minus",
  "mouse-pointer-click",
  "panel-top",
  "pilcrow",
  "play",
  "plus",
  "quote",
  "redo-2",
  "settings",
  "square",
  "strikethrough",
  "table",
  "table-rows-split",
  "text-align-center",
  "text-align-end",
  "text-align-start",
  "trash-2",
  "underline",
  "undo-2",
  "unlink",
  "x",
]

const entries = icons.map((name) => {
  const svg = readFileSync(join(root, `${name}.svg`), "utf8")
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s*\n\s*/g, "")
  return `  "${name}": '${inner}',`
})

writeFileSync(
  new URL("../resources/js/editor/ui/icons.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from lucide-static (ISC). Don't edit by hand.

export const ICONS: Record<string, string> = {
${entries.join("\n")}
}
`,
)
